#!/usr/bin/env python3
"""Generates src/core/LanguageSetupStrings.cpp from the AddStringRec calls in
LanguageSetupUnit.pas (TLanguageSetup.SetupLanguageStrings1..5)."""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pas2h  # noqa: E402

src, out = sys.argv[1:3]
text = open(src, encoding='cp1252', errors='replace').read()
text = pas2h.strip_comments(text)
res = ['// Generated by tools/langstrings.py from LanguageSetupUnit.pas - do not edit.',
       '// Default (English) language strings of D-Fend Reloaded.',
       '#include "LanguageSetupUnit.h"', '#include "PrgConsts.h"', '']
# Delphi identifiers are case insensitive: use the spelling of the declarations
hdr = open(os.path.join(os.path.dirname(os.path.abspath(out)), 'LanguageSetupUnit.h'), encoding='utf-8').read()
canon = {m.lower(): m for m in re.findall(r'\bNR_\w+', hdr)}
for n in range(1, 6):
    m = re.search(r'Procedure\s+TLanguageSetup\.SetupLanguageStrings%d\s*;\s*begin(.*?)\nend;' % n, text, re.S | re.I)
    body = m.group(1)
    toks = pas2h.tokenize(body)
    res.append(f'void TLanguageSetup::SetupLanguageStrings{n}()')
    res.append('{')
    i = 0
    count = 0
    while i < len(toks):
        k, v = toks[i]
        if k == 'id' and v.lower() == 'addstringrec':
            i += 2  # name + '('
            args = []
            cur = []
            depth = 0
            while True:
                k2, v2 = toks[i]
                if v2 == '(':
                    depth += 1
                elif v2 == ')':
                    if depth == 0:
                        break
                    depth -= 1
                if v2 == ',' and depth == 0:
                    args.append(cur)
                    cur = []
                else:
                    cur.append((k2, v2))
                i += 1
            args.append(cur)
            cargs = [pas2h.expr_to_cpp(a) for a in args]
            cargs[0] = canon.get(cargs[0].lower(), cargs[0])
            res.append(f'    AddStringRec({", ".join(cargs)});')
            count += 1
        i += 1
    res.append('}')
    res.append('')
    print(f'SetupLanguageStrings{n}: {count} strings', file=sys.stderr)
open(out, 'w', encoding='utf-8').write('\n'.join(res))
